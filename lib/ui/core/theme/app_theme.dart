import 'package:material_ui/material_ui.dart';

const Color _brand = Color(0xFF2B4BEB);
const BorderRadius _radius = BorderRadius.all(Radius.circular(16));
const RoundedRectangleBorder _shape = RoundedRectangleBorder(
  borderRadius: _radius,
);
const Size _buttonSize = Size.fromHeight(56);

/// Material 3 theme for TaskFlow. Widgets read colors, text styles and
/// component styles from here via `Theme.of(context)`, never hardcoded.
abstract final class AppTheme {
  /// Light scheme generated from the brand color, with a few roles pinned
  /// to match the design mockup exactly.
  static final ThemeData light = _buildTheme(
    ColorScheme.fromSeed(
      seedColor: _brand,
      dynamicSchemeVariant: DynamicSchemeVariant.fidelity,
    ).copyWith(
      primary: _brand,
      surface: Colors.white,
      onSurface: const Color(0xFF111827),
      onSurfaceVariant: const Color(0xFF6B7280),
      outline: const Color(0xFF9CA3AF),
      outlineVariant: const Color(0xFFE5E7EB),
      surfaceContainerLow: const Color(0xFFFAFAFA),
    ),
  );

  /// Dark scheme fully generated by M3 from the same brand color.
  static final ThemeData dark = _buildTheme(
    ColorScheme.fromSeed(
      seedColor: _brand,
      brightness: Brightness.dark,
      dynamicSchemeVariant: DynamicSchemeVariant.fidelity,
    ),
  );
}

/// Returns the app theme for [scheme], with TaskFlow's text weights and
/// component styles applied on top of the M3 defaults.
ThemeData _buildTheme(ColorScheme scheme) {
  final ThemeData base = ThemeData(colorScheme: scheme);
  final TextTheme text = _buildTextTheme(base.textTheme);

  return base.copyWith(
    textTheme: text,
    filledButtonTheme: FilledButtonThemeData(
      style: FilledButton.styleFrom(
        minimumSize: _buttonSize,
        shape: _shape,
        textStyle: text.labelLarge,
      ),
    ),
    outlinedButtonTheme: OutlinedButtonThemeData(
      style: OutlinedButton.styleFrom(
        minimumSize: _buttonSize,
        shape: _shape,
        textStyle: text.labelLarge,
        foregroundColor: scheme.onSurface,
        side: BorderSide(color: scheme.outlineVariant),
      ),
    ),
    textButtonTheme: TextButtonThemeData(
      style: TextButton.styleFrom(textStyle: text.labelLarge),
    ),
    inputDecorationTheme: _buildInputDecorationTheme(scheme, text),
    dividerTheme: DividerThemeData(color: scheme.outlineVariant),
  );
}

/// Returns [base] with bolder headlines and larger, semi-bold button labels
/// to match the design mockup.
TextTheme _buildTextTheme(TextTheme base) {
  return base.copyWith(
    headlineLarge: base.headlineLarge?.copyWith(fontWeight: FontWeight.w700),
    headlineSmall: base.headlineSmall?.copyWith(fontWeight: FontWeight.w700),
    titleSmall: base.titleSmall?.copyWith(fontWeight: FontWeight.w600),
    labelLarge: base.labelLarge?.copyWith(
      fontSize: 16,
      fontWeight: FontWeight.w600,
    ),
  );
}

/// Returns the style of filled, rounded text fields whose border highlights
/// the focused and the invalid state.
InputDecorationThemeData _buildInputDecorationTheme(
  ColorScheme scheme,
  TextTheme text,
) {
  return InputDecorationThemeData(
    filled: true,
    fillColor: scheme.surfaceContainerLow,
    hintStyle: text.bodyLarge?.copyWith(color: scheme.outline),
    prefixIconColor: scheme.outline,
    suffixIconColor: scheme.outline,
    contentPadding: const EdgeInsets.symmetric(vertical: 18),
    border: _border(scheme.outlineVariant),
    enabledBorder: _border(scheme.outlineVariant),
    disabledBorder: _border(scheme.outlineVariant),
    focusedBorder: _border(scheme.primary, 1.5),
    errorBorder: _border(scheme.error),
    focusedErrorBorder: _border(scheme.error, 1.5),
  );
}

/// Returns a rounded text field border drawn in [color] with [width].
OutlineInputBorder _border(Color color, [double width = 1]) {
  return OutlineInputBorder(
    borderRadius: _radius,
    borderSide: BorderSide(color: color, width: width),
  );
}
